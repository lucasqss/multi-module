CREATE TABLE gar_garantia (
    id                  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cota_ref            VARCHAR2(30)  NOT NULL,
    tipo                VARCHAR2(30)  NOT NULL,
    origem              VARCHAR2(30)  NOT NULL,
    processo_ref        NUMBER,
    objeto_ref          NUMBER,
    instrumento_ref     NUMBER,
    valor_cobertura     NUMBER(15, 2) NOT NULL,
    situacao            VARCHAR2(20)  NOT NULL,
    chave_idempotencia  VARCHAR2(100),
    CONSTRAINT uk_gar_chave UNIQUE (chave_idempotencia)
);

CREATE TABLE gar_fiador (
    id           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    garantia_id  NUMBER        NOT NULL REFERENCES gar_garantia (id),
    cpf_cnpj     VARCHAR2(14)  NOT NULL,
    nome         VARCHAR2(200) NOT NULL
);

CREATE TABLE gar_registro (
    id               NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    garantia_id      NUMBER        NOT NULL REFERENCES gar_garantia (id),
    orgao            VARCHAR2(100) NOT NULL,
    protocolo        VARCHAR2(60),
    numero_registro  VARCHAR2(60),
    registrado_em    DATE,
    conferido_por    VARCHAR2(60)
);

CREATE TABLE gar_evento (
    id           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    garantia_id  NUMBER       NOT NULL REFERENCES gar_garantia (id),
    tipo         VARCHAR2(40) NOT NULL,
    ator         VARCHAR2(60) NOT NULL,
    em           TIMESTAMP    NOT NULL
);
