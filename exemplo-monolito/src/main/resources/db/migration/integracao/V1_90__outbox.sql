CREATE TABLE int_outbox (
    id                  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo                VARCHAR2(40)  NOT NULL,
    referencia_id       NUMBER        NOT NULL,
    chave_idempotencia  VARCHAR2(100) NOT NULL,
    payload             CLOB          NOT NULL,
    situacao            VARCHAR2(20)  NOT NULL CHECK (situacao IN ('PENDENTE', 'ENVIADA', 'FALHOU')),
    tentativas          NUMBER(3)     DEFAULT 0 NOT NULL,
    ultimo_erro         VARCHAR2(1000),
    criado_em           TIMESTAMP     NOT NULL,
    enviado_em          TIMESTAMP,
    CONSTRAINT uk_int_outbox_chave UNIQUE (chave_idempotencia)
);
