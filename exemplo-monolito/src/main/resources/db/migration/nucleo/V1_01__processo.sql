-- Dono: dominio.nucleo.processo. As subtabelas de cada modalidade ficam nas migrações do plug-in.
CREATE TABLE prc_processo (
    id                     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_processo          VARCHAR2(30) NOT NULL,
    categoria              VARCHAR2(20) NOT NULL CHECK (categoria IN ('IMOVEL', 'MOVEL_I', 'MOVEL_II', 'SERVICO')),
    finalidade             VARCHAR2(30) NOT NULL,
    estado                 VARCHAR2(30) NOT NULL,
    roteiro_codigo         VARCHAR2(60) NOT NULL,
    roteiro_versao         NUMBER(3)    NOT NULL,
    titular_pessoa_id      NUMBER       NOT NULL REFERENCES pes_pessoa (id),
    comunicacao_formal_em  TIMESTAMP,
    versao                 NUMBER(10)   DEFAULT 0 NOT NULL
);

CREATE TABLE prc_objeto (
    id                          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    processo_id                 NUMBER        NOT NULL REFERENCES prc_processo (id),
    tipo_objeto                 VARCHAR2(30)  NOT NULL,
    descricao                   VARCHAR2(400),
    valor_negociado             NUMBER(15, 2) NOT NULL,
    valor_avaliado              NUMBER(15, 2),
    fornecedor_participacao_id  NUMBER
);

CREATE TABLE prc_contato_acesso (
    id         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    objeto_id  NUMBER        NOT NULL REFERENCES prc_objeto (id),
    nome       VARCHAR2(200) NOT NULL,
    email      VARCHAR2(200),
    telefone   VARCHAR2(30)
);

CREATE TABLE prc_etapa (
    id             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    processo_id    NUMBER       NOT NULL REFERENCES prc_processo (id),
    codigo_fase    VARCHAR2(40) NOT NULL,
    ordem          NUMBER(3)    NOT NULL,
    situacao       VARCHAR2(20) NOT NULL,
    concluida_em   TIMESTAMP,
    concluida_por  VARCHAR2(60),
    CONSTRAINT uk_prc_etapa UNIQUE (processo_id, codigo_fase)
);

CREATE TABLE prc_historico (
    id           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    processo_id  NUMBER       NOT NULL REFERENCES prc_processo (id),
    entidade     VARCHAR2(30) NOT NULL,
    entidade_id  NUMBER       NOT NULL,
    de           VARCHAR2(40),
    para         VARCHAR2(40) NOT NULL,
    motivo       VARCHAR2(400),
    ator         VARCHAR2(60) NOT NULL,
    em           TIMESTAMP    NOT NULL
);

-- Participação referencia o processo: criada aqui porque depende de prc_processo.
CREATE TABLE pes_participacao (
    id           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    processo_id  NUMBER       NOT NULL REFERENCES prc_processo (id),
    pessoa_id    NUMBER       NOT NULL REFERENCES pes_pessoa (id),
    papel        VARCHAR2(30) NOT NULL,
    CONSTRAINT uk_pes_participacao UNIQUE (processo_id, pessoa_id, papel)
);

CREATE TABLE pes_conta_recebimento (
    id                       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    participacao_id          NUMBER NOT NULL REFERENCES pes_participacao (id),
    banco                    VARCHAR2(3),
    agencia                  VARCHAR2(10),
    conta                    VARCHAR2(20),
    chave_pix                VARCHAR2(100),
    titularidade_verificada  CHAR(1) DEFAULT 'N' NOT NULL CHECK (titularidade_verificada IN ('S', 'N'))
);
