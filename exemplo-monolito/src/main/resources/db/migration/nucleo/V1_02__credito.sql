CREATE TABLE cre_processo_cota (
    id               NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    processo_id      NUMBER        NOT NULL REFERENCES prc_processo (id),
    cota_ref         VARCHAR2(30)  NOT NULL,
    situacao         VARCHAR2(20)  NOT NULL CHECK (situacao IN ('RESERVADA', 'UTILIZADA', 'LIBERADA')),
    valor_reservado  NUMBER(15, 2) NOT NULL,
    valor_utilizado  NUMBER(15, 2) DEFAULT 0 NOT NULL,
    snapshot_saldo   NUMBER(15, 2) NOT NULL,
    snapshot_em      TIMESTAMP     NOT NULL,
    versao           NUMBER(10)    DEFAULT 0 NOT NULL
);

-- Uma cota só pode estar RESERVADA em um processo por vez.
CREATE UNIQUE INDEX ux_cre_cota_ativa
    ON cre_processo_cota (CASE WHEN situacao = 'RESERVADA' THEN cota_ref END);

CREATE TABLE cre_recurso (
    id           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    processo_id  NUMBER        NOT NULL REFERENCES prc_processo (id),
    tipo         VARCHAR2(30)  NOT NULL CHECK (tipo IN ('RECURSOS_PROPRIOS', 'FGTS', 'SINAL')),
    valor        NUMBER(15, 2) NOT NULL,
    liquidacao   VARCHAR2(30)  NOT NULL CHECK (liquidacao IN ('DIRETO_AO_VENDEDOR', 'VIA_ADMINISTRADORA')),
    situacao     VARCHAR2(20)  NOT NULL
);
