-- Dono: dominio.nucleo.documento.
CREATE TABLE doc_documento (
    id               NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_documento   VARCHAR2(60)  NOT NULL,
    id_ged           VARCHAR2(100) NOT NULL,
    nome_arquivo     VARCHAR2(200) NOT NULL,
    mime             VARCHAR2(100) NOT NULL,
    situacao         VARCHAR2(20)  NOT NULL,
    objeto_id        NUMBER REFERENCES prc_objeto (id),
    participacao_id  NUMBER REFERENCES pes_participacao (id),
    processo_id      NUMBER REFERENCES prc_processo (id),
    instrumento_id   NUMBER REFERENCES ins_instrumento (id),
    CONSTRAINT ck_doc_dono_unico CHECK (
        NVL2(objeto_id, 1, 0) + NVL2(participacao_id, 1, 0)
        + NVL2(processo_id, 1, 0) + NVL2(instrumento_id, 1, 0) = 1)
);
