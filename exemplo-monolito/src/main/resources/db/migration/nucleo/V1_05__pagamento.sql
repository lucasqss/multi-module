CREATE TABLE pag_ordem (
    id                            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    processo_id                   NUMBER        NOT NULL REFERENCES prc_processo (id),
    beneficiario_participacao_id  NUMBER        NOT NULL REFERENCES pes_participacao (id),
    conta_recebimento_id          NUMBER        NOT NULL REFERENCES pes_conta_recebimento (id),
    finalidade_ordem              VARCHAR2(30)  NOT NULL,
    meio                          VARCHAR2(10)  NOT NULL CHECK (meio IN ('TED', 'PIX')),
    valor                         NUMBER(15, 2) NOT NULL,
    situacao                      VARCHAR2(20)  NOT NULL,
    preparada_por                 VARCHAR2(60)  NOT NULL,
    aprovada_por                  VARCHAR2(60),
    id_externo                    VARCHAR2(100),
    versao                        NUMBER(10)    DEFAULT 0 NOT NULL,
    CONSTRAINT ck_pag_quatro_olhos CHECK (aprovada_por IS NULL OR aprovada_por <> preparada_por)
);

CREATE TABLE pag_ordem_origem (
    id                NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ordem_id          NUMBER        NOT NULL REFERENCES pag_ordem (id),
    processo_cota_id  NUMBER REFERENCES cre_processo_cota (id),
    recurso_id        NUMBER REFERENCES cre_recurso (id),
    valor             NUMBER(15, 2) NOT NULL CHECK (valor > 0),
    CONSTRAINT ck_pag_origem_unica CHECK (NVL2(processo_cota_id, 1, 0) + NVL2(recurso_id, 1, 0) = 1)
);

CREATE TABLE pag_retorno (
    id                  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ordem_id            NUMBER REFERENCES pag_ordem (id),
    chave_idempotencia  VARCHAR2(100) NOT NULL,
    resultado           VARCHAR2(20)  NOT NULL,
    recebido_em         TIMESTAMP     NOT NULL,
    CONSTRAINT uk_pag_retorno_chave UNIQUE (chave_idempotencia)
);
