CREATE TABLE LIVRO (
    ID        RAW(16)       NOT NULL,
    ISBN      VARCHAR2(13)  NOT NULL,
    TITULO    VARCHAR2(255) NOT NULL,
    SUBTITULO VARCHAR2(255),
    EDICAO    NUMBER(10)    NOT NULL,
    LOCAL     VARCHAR2(255),
    EDITORA   VARCHAR2(255),
    ANO       NUMBER(10)    NOT NULL,
    CONSTRAINT PK_LIVRO PRIMARY KEY (ID),
    CONSTRAINT UK_LIVRO_ISBN UNIQUE (ISBN)
);

CREATE TABLE LIVRO_AUTOR (
    ID       RAW(16)       NOT NULL,
    LIVRO_ID RAW(16)       NOT NULL,
    ORDEM    NUMBER(10)    NOT NULL,
    NOME     VARCHAR2(255) NOT NULL,
    CONSTRAINT PK_LIVRO_AUTOR PRIMARY KEY (ID),
    CONSTRAINT UK_LIVRO_AUTOR_ORDEM UNIQUE (LIVRO_ID, ORDEM),
    CONSTRAINT FK_LIVRO_AUTOR_LIVRO FOREIGN KEY (LIVRO_ID) REFERENCES LIVRO (ID)
);

CREATE TABLE EXEMPLAR (
    ID       RAW(16)      NOT NULL,
    LIVRO_ID RAW(16)      NOT NULL,
    TOMBO    VARCHAR2(30) NOT NULL,
    SITUACAO VARCHAR2(20) NOT NULL,
    CONSTRAINT PK_EXEMPLAR PRIMARY KEY (ID),
    CONSTRAINT UK_EXEMPLAR_TOMBO UNIQUE (TOMBO),
    CONSTRAINT FK_EXEMPLAR_LIVRO FOREIGN KEY (LIVRO_ID) REFERENCES LIVRO (ID),
    CONSTRAINT CK_EXEMPLAR_SITUACAO CHECK (SITUACAO IN ('DISPONIVEL', 'EMPRESTADO', 'BAIXADO'))
);

CREATE TABLE LEITOR (
    ID           RAW(16)       NOT NULL,
    NOME         VARCHAR2(255) NOT NULL,
    EMAIL        VARCHAR2(255) NOT NULL,
    SUSPENSO_ATE DATE,
    CONSTRAINT PK_LEITOR PRIMARY KEY (ID),
    CONSTRAINT UK_LEITOR_EMAIL UNIQUE (EMAIL)
);

CREATE TABLE EMPRESTIMO (
    ID              RAW(16)    NOT NULL,
    LEITOR_ID       RAW(16)    NOT NULL,
    EXEMPLAR_ID     RAW(16)    NOT NULL,
    DATA_EMPRESTIMO DATE       NOT NULL,
    DATA_PREVISTA   DATE       NOT NULL,
    RENOVACOES      NUMBER(10) NOT NULL,
    DATA_DEVOLUCAO  DATE,
    CONSTRAINT PK_EMPRESTIMO PRIMARY KEY (ID),
    CONSTRAINT FK_EMPRESTIMO_LEITOR FOREIGN KEY (LEITOR_ID) REFERENCES LEITOR (ID),
    CONSTRAINT FK_EMPRESTIMO_EXEMPLAR FOREIGN KEY (EXEMPLAR_ID) REFERENCES EXEMPLAR (ID)
);

-- Rede de segurança contra corrida: no máximo um empréstimo aberto por exemplar
CREATE UNIQUE INDEX UK_EMPRESTIMO_ABERTO ON EMPRESTIMO (CASE WHEN DATA_DEVOLUCAO IS NULL THEN EXEMPLAR_ID END);
CREATE INDEX IX_EMPRESTIMO_LEITOR ON EMPRESTIMO (LEITOR_ID);
