-- Numeração única para todos os segmentos: o número do processo é <prefixo do segmento>-<ano>-<sequencial>
CREATE SEQUENCE SEQ_NUMERO_PROCESSO START WITH 1 INCREMENT BY 1 NOCACHE;

-- Pai: dados comuns a todo processo, qualquer que seja o segmento
CREATE TABLE PROCESSO (
    ID              RAW(16)       NOT NULL,
    NUMERO          VARCHAR2(30)  NOT NULL,
    SEGMENTO        VARCHAR2(30)  NOT NULL,
    PROPONENTE_NOME VARCHAR2(255) NOT NULL,
    PROPONENTE_CPF  VARCHAR2(11)  NOT NULL,
    VALOR           NUMBER(15, 2) NOT NULL,
    SITUACAO        VARCHAR2(20)  NOT NULL,
    DATA_ABERTURA   DATE          NOT NULL,
    CONSTRAINT PK_PROCESSO PRIMARY KEY (ID),
    CONSTRAINT UK_PROCESSO_NUMERO UNIQUE (NUMERO),
    CONSTRAINT CK_PROCESSO_SITUACAO CHECK (SITUACAO IN ('ABERTO', 'CONCLUIDO', 'CANCELADO'))
);

-- Filha do segmento imobiliário: mesma PK do pai (herança JOINED)
CREATE TABLE PROCESSO_IMOBILIARIO (
    PROCESSO_ID     RAW(16)       NOT NULL,
    MATRICULA       VARCHAR2(20)  NOT NULL,
    TIPO_IMOVEL     VARCHAR2(20)  NOT NULL,
    VALOR_AVALIACAO NUMBER(15, 2) NOT NULL,
    UF              VARCHAR2(2)   NOT NULL,
    CONSTRAINT PK_PROCESSO_IMOBILIARIO PRIMARY KEY (PROCESSO_ID),
    CONSTRAINT FK_PROCESSO_IMOBILIARIO FOREIGN KEY (PROCESSO_ID) REFERENCES PROCESSO (ID),
    CONSTRAINT CK_PROCESSO_IMOBILIARIO_TIPO CHECK (TIPO_IMOVEL IN ('RESIDENCIAL', 'COMERCIAL'))
);

CREATE INDEX IX_PROCESSO_IMOBILIARIO_MATRICULA ON PROCESSO_IMOBILIARIO (MATRICULA, UF);
